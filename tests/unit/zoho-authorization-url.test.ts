import { describe, expect, it } from "vitest";
import { buildZohoAuthorizationUrl } from "../../src/integrations/zoho/authorization-url.js";
import { generatePkcePair } from "../../src/integrations/zoho/pkce.js";

describe("Zoho authorization URL builder", () => {
  // Reuse a valid set of inputs so each test can focus on one behaviour.
  const validOptions = {
    accountsUrl: "https://accounts.zoho.com",
    clientId: "test-client-id",
    redirectUri: "http://localhost:3000/integrations/zoho/callback",
    state: "test-random-state",
    codeChallenge: "test-pkce-challenge",
  };

  it("builds the expected Zoho authorization URL", () => {
    const url = buildZohoAuthorizationUrl(validOptions);

    // Check the destination separately from its query parameters.
    expect(url.origin).toBe("https://accounts.zoho.com");
    expect(url.pathname).toBe("/oauth/v2/auth");

    // Verify the required OAuth parameters.
    expect(url.searchParams.get("client_id")).toBe("test-client-id");
    expect(url.searchParams.get("response_type")).toBe("code");
    expect(url.searchParams.get("redirect_uri")).toBe(
      "http://localhost:3000/integrations/zoho/callback",
    );
    expect(url.searchParams.get("scope")).toBe("ZohoBooks.invoices.READ");
    expect(url.searchParams.get("access_type")).toBe("offline");
    expect(url.searchParams.get("state")).toBe("test-random-state");
    expect(url.searchParams.get("code_challenge")).toBe("test-pkce-challenge");
    expect(url.searchParams.get("code_challenge_method")).toBe("S256");
  });

  it("supports a different Zoho Accounts data-center URL", () => {
    const url = buildZohoAuthorizationUrl({
      ...validOptions,
      accountsUrl: "https://accounts.zoho.eu",
    });

    expect(url.origin).toBe("https://accounts.zoho.eu");
  });

  it("rejects blank required parameters", () => {
    expect(() =>
      buildZohoAuthorizationUrl({
        ...validOptions,
        clientId: "   ",
      }),
    ).toThrow("Zoho authorization URL parameters must not be blank");
  });

  it.each([
    "https://accounts.zoho.com",
    "https://accounts.zoho.eu",
    "https://accounts.zoho.in",
    "https://accounts.zoho.com.au",
    "https://accounts.zoho.jp",
    "https://accounts.zoho.com.cn",
    "https://accounts.zoho.sa",
    "https://accounts.zoho.uk",
    "https://accounts.zohocloud.ca",
  ])("accepts the official Zoho Accounts URL %s", (accountsUrl) => {
    expect(() =>
      buildZohoAuthorizationUrl({
        ...validOptions,
        accountsUrl,
      }),
    ).not.toThrow();
  });

  it.each([
    "https://accounts.example.com",
    "https://accounts.zoho.com.attacker.example",
    "https://zoho.com",
  ])("rejects an untrusted authorization server URL: %s", (accountsUrl) => {
    expect(() =>
      buildZohoAuthorizationUrl({
        ...validOptions,
        accountsUrl,
      }),
    ).toThrow("Zoho Accounts URL must be an official HTTPS endpoint");
  });

  it("rejects an authorization server URL that does not use HTTPS", () => {
    expect(() =>
      buildZohoAuthorizationUrl({
        ...validOptions,
        accountsUrl: "http://accounts.zoho.com",
      }),
    ).toThrow("Zoho Accounts URL must use HTTPS");
  });

  it("rejects a non-local HTTP redirect URI", () => {
    expect(() =>
      buildZohoAuthorizationUrl({
        ...validOptions,
        redirectUri: "http://example.com/callback",
      }),
    ).toThrow("Zoho redirect URI must use HTTPS, except for localhost development");
  });

  it("uses the generated PKCE challenge in the authorization URL", () => {
    // Generate a real verifier/challenge pair.
    const pkce = generatePkcePair();

    // Pass the challenge into the URL builder.
    const url = buildZohoAuthorizationUrl({
      ...validOptions,
      codeChallenge: pkce.challenge,
    });

    // The URL must contain the challenge generated by our PKCE helper.
    expect(url.searchParams.get("code_challenge")).toBe(pkce.challenge);

    // The request must specify the S256 challenge method.
    expect(url.searchParams.get("code_challenge_method")).toBe("S256");

    // The secret verifier must not be sent in the authorization URL.
    expect(url.searchParams.has("code_verifier")).toBe(false);
  });
});
